// Strict compiler probes for the environment/secret-storage boundary: the
// secret-key catalog is a literal union (no free string index), crypto
// buffers are Buffer-typed, and wrong usage fails compilation. Codes were
// verified against an actual strict tsc run.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const root = path.resolve(__dirname, "../..");
const configPath = path.join(root, "tsconfig.main.json");

function probeDiagnostics(source) {
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
  assert.equal(parsed.options.strict, true);
  const probe = path.join(root, "env-secret-type-probe.ts");
  const host = ts.createCompilerHost(parsed.options);
  const readSource = host.getSourceFile.bind(host);
  host.getSourceFile = (file, languageVersion, ...args) =>
    file === probe
      ? ts.createSourceFile(file, source, languageVersion, true)
      : readSource(file, languageVersion, ...args);
  const program = ts.createProgram([probe], { ...parsed.options, noEmit: true }, host);
  const diagnostics = ts.getPreEmitDiagnostics(program);
  return {
    codes: diagnostics.map((d) => d.code).sort((a, b) => a - b),
    cleanup: () => {
      if (fs.existsSync(probe)) fs.rmSync(probe, { force: true });
    },
  };
}

test("wrong secret-storage usage fails compilation", () => {
  const { codes, cleanup } = probeDiagnostics(`
import { EnvironmentManager } from "./src/helpers/environment.ts";
import { encrypt, decrypt, isAvailable } from "./src/helpers/secretCrypto.ts";
import { BYOK_API_KEYS } from "./src/config/secretKeys.ts";

// Encryption takes a string, not a buffer.
encrypt(Buffer.from("not plaintext"));

// Decryption returns { value, needsReencrypt }, not a bare string.
const value: string = decrypt(Buffer.from("blob"));

// isAvailable is a boolean probe without arguments.
isAvailable("please");

// The manager constructor takes no options object.
new EnvironmentManager({ persistent: true });

// Manifest entries carry the catalog fields — accessing a fantasy field
// must fail instead of resolving through a string index.
for (const entry of BYOK_API_KEYS) {
  const fantasy: string = entry.notInTheCatalog;
  void fantasy;
}
void value;
`);
  try {
    assert.ok(codes.length > 0, "wrong usage must not compile");
    // Verified against an actual strict run: TS2345 (buffer→string arg),
    // TS2322 (DecryptResult→string), TS2554 ×2 (arity), TS2339 (catalog typo).
    assert.equal(codes.filter((code) => code === 2345).length, 1);
    assert.equal(codes.filter((code) => code === 2322).length, 1);
    assert.equal(codes.filter((code) => code === 2554).length, 2);
    assert.ok(codes.includes(2339), `catalog typo must fail, got ${codes.join(",")}`);
  } finally {
    cleanup();
  }
});

test("the environment/secret graph compiles under strict settings", () => {
  const { codes, cleanup } = probeDiagnostics(`
import { EnvironmentManager, type EnvironmentManagerWithByok } from "./src/helpers/environment.ts";
import { encrypt, decrypt, isAvailable, type DecryptResult } from "./src/helpers/secretCrypto.ts";
import { BYOK_API_KEYS, type ByokApiKeyEntry } from "./src/config/secretKeys.ts";

async function useAll(): Promise<string> {
  // The BYOK accessors are attached at runtime from the catalog; the exported
  // type documents that surface for typed consumers.
  const manager = new EnvironmentManager() as EnvironmentManagerWithByok;
  await manager.init();
  void manager.loadEnvironmentVariables();
  void manager.getCortiClientId();
  void manager.saveCortiClientId("id");
  void manager.getBedrockRegion();
  void manager.saveBedrockRegion("eu-west-1");
  void manager.getAzureEndpoint();
  void manager.getVertexProject();
  void manager.getDictationKey();
  void manager.saveDictationKey("k");
  void manager.getVoiceAgentKey();
  void manager.getActivationMode();
  void manager.getFloatingIconAutoHide();
  void manager.getPanelStartPosition();
  void manager.getUiLanguage("en");
  const saved = await manager.saveAllKeysToEnvFile();
  await manager.clearAllPersistedData();
  void manager.removeKeyFromEnvFile("OPENAI_API_KEY");

  // Generated BYOK accessors are part of the typed surface; entry names stay
  // literal through the const catalog.
  const entry: (typeof BYOK_API_KEYS)[number] = BYOK_API_KEYS[0];
  manager[entry.get]();
  const store: string = manager[entry.get]();
  manager[entry.save]("synthetic");
  void store;
  const annotated: ByokApiKeyEntry = BYOK_API_KEYS[0];
  void annotated.storeKey;

  const blob: Buffer = encrypt("synthetic");
  const result: DecryptResult = decrypt(blob);
  const roundTrips: boolean = result.value === "synthetic" && !result.needsReencrypt;
  void isAvailable();
  return [saved.path, String(roundTrips)].join();
}
void useAll;
`);
  try {
    assert.deepEqual(codes, []);
  } finally {
    cleanup();
  }
});
