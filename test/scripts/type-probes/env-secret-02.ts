import { EnvironmentManager, type EnvironmentManagerWithByok } from "./src/helpers/environment.ts";
import { encrypt, decrypt, isAvailable, type DecryptResult } from "./src/helpers/secretCrypto.ts";
import { BYOK_API_KEYS, type ByokApiKeyEntry } from "./src/config/secretKeys.ts";

async function useAll(): Promise<string> {
  // The BYOK accessors are attached at runtime from the catalog; the exported
  // type documents that surface for typed consumers.
  const manager = new EnvironmentManager() as EnvironmentManagerWithByok;
  await manager.init();
  void manager.loadEnvironmentVariables();
  void manager.getCortiClientId();
  void manager.saveCortiClientId("id");
  void manager.getBedrockRegion();
  void manager.saveBedrockRegion("eu-west-1");
  void manager.getAzureEndpoint();
  void manager.getVertexProject();
  void manager.getDictationKey();
  void manager.saveDictationKey("k");
  void manager.getVoiceAgentKey();
  void manager.getActivationMode();
  void manager.getFloatingIconAutoHide();
  void manager.getPanelStartPosition();
  void manager.getUiLanguage("en");
  const saved = await manager.saveAllKeysToEnvFile();
  await manager.clearAllPersistedData();
  void manager.removeKeyFromEnvFile("OPENAI_API_KEY");

  // Generated BYOK accessors are part of the typed surface; entry names stay
  // literal through the const catalog.
  const entry: (typeof BYOK_API_KEYS)[number] = BYOK_API_KEYS[0];
  manager[entry.get]();
  const store: string = manager[entry.get]();
  manager[entry.save]("synthetic");
  void store;
  const annotated: ByokApiKeyEntry = BYOK_API_KEYS[0];
  void annotated.storeKey;

  const blob: Buffer = encrypt("synthetic");
  const result: DecryptResult = decrypt(blob);
  const roundTrips: boolean = result.value === "synthetic" && !result.needsReencrypt;
  void isAvailable();
  return [saved.path, String(roundTrips)].join();
}
void useAll;
